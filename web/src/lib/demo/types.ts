export type ScenarioId = "A_main" | "A_lowconf" | "A_noanswer" | "B_memo" | "REFUSE";
export type ChoiceKey = "A" | "B" | "REFUSE";

export type ActionKey =
  | "shipper:choose"
  | "shipper:memo"
  | "shipper:delivered"
  | "buyer:answer"
  | "cs:approve";

export type Actor = "agent" | "buyer" | "shipper" | "cs" | "system";

export type ChatMsg = {
  id: string;
  from: "agent" | "buyer" | "system";
  text: string;
  at: number;
  options?: string[];
  picked?: string;
};

export type CallLine = {
  id: string;
  who: "ai" | "buyer";
  text: string;
  at: number;
  /** pre-recorded fixed phrase, or a dynamic part generated by TTS */
  voice?: "recorded" | "tts";
};

export type CallState = {
  status: "idle" | "ringing" | "connected" | "ended" | "missed";
  attempt: number;
  lines: CallLine[];
  durationS?: number;
};

export type ShipperScreen =
  | "route"
  | "calling"
  | "choose"
  | "waiting"
  | "memo"
  | "context"
  | "delivered"
  | "handoff";

export type CaseStage =
  | "pre"
  | "delivering"
  | "chat"
  | "call1"
  | "call2"
  | "extract"
  | "ready"
  | "review"
  | "cs"
  | "closed";

export type AuditEntry = {
  id: string;
  at: number;
  actor: Actor;
  text: string;
  tone?: "good" | "warn" | "bad";
};

export type ExtractField = {
  key: "time_window" | "drop_location" | "alt_receiver" | "address_correction";
  label: string;
  value: string | null;
  conf: number | null;
};

export type Extraction = {
  source: "chat" | "ai_call" | "shipper_memo";
  fields: ExtractField[];
  revealed: number;
  decision: "auto_applied" | "needs_review" | "escalated_cs" | null;
};

export type ContextCard = {
  window: string;
  drop: string;
  alt: string | null;
  source: string;
  by: "agent" | "cs";
};

export type MemoState = {
  status: "idle" | "recording" | "done";
  seconds: number;
  transcript?: string;
};

export type OrderContext = {
  tracking_id: string;
  version: number;
  trigger: "PRE_DELIVERY" | "NO_ANSWER" | "RESCHEDULE" | "REFUSED";
  rescue_cycle: number;
  delivery_attempt: number;
  channel: "chat_shopee" | "zalo" | "ai_call" | "shipper_memo" | null;
  contact_log: { at: string; type: string; result?: string; duration_s?: number }[];
  slots_offered: string[];
  extracted: {
    time_window: { date: string; from: string; to: string } | null;
    drop_location: { type: string; note: string } | null;
    alt_receiver: { phone: string; relation: string } | null;
    address_correction: string | null;
  };
  confidence: Record<string, number>;
  decision: "pending" | "auto_applied" | "needs_review" | "escalated_cs" | "cs_applied";
  consent: { recording: boolean | null; opt_out: boolean };
  raw_ref: string | null;
  updated_by: "agent" | "buyer" | "shipper" | "cs" | "system";
};

export type DemoState = {
  scenario: ScenarioId;
  step: number;
  clock: number;
  playing: boolean;
  auto: boolean;
  speed: number;
  waitingFor: { action: ActionKey; hint: string } | null;
  caption: string;
  shipper: { screen: ShipperScreen; day: 0 | 1; banner?: string };
  memo: MemoState;
  chat: ChatMsg[];
  buyerTyping: boolean;
  call: CallState;
  stage: CaseStage;
  timer: { label: string; until: number } | null;
  extraction: Extraction | null;
  card: ContextCard | null;
  oco: OrderContext;
  prevOco: OrderContext | null;
  audit: AuditEntry[];
  guard: { contacts: number; maxCalls: number; calls: number; consent: boolean | null; optOut: boolean };
  ttc: { triggerAt: number | null; contextAt: number | null; lastSignalAt: number | null };
  done: boolean;
  /** clock target while fast-forwarding, so another tab can take over mid-step without drift */
  animTo: number | null;
};

export type Step = {
  id: string;
  /** demo-clock minutes fast-forwarded during this step */
  dt?: number;
  /** or jump to an absolute demo-clock time (minutes from 00:00 on 31 Oct) */
  to?: number;
  /** real time (ms at 1x) before the step applies */
  ms?: number;
  caption?: string;
  wait?: { action: ActionKey; hint: string; autoMs?: number };
  apply?: (s: DemoState, payload?: string) => DemoState;
};
