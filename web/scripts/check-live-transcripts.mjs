// Replays the observed e489b18c application-event shape; no provider call.
import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import ts from "typescript";
const exported = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(new URL("../src/lib/ai/live-demo.ts", import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports: exported, require: () => ({}), URL, URLSearchParams });
const timeline = new exported.LiveTranscriptTimeline();
const greeting = "Xin chào, bạn muốn nhận hàng vào ngày giờ nào và ở địa điểm nào?";
const buyer = " Please reschedule my delivery to tomorrow, November 1st, from 5 pm to 8 pm, and leave it with the security desk Please call when arriving";
const prefix = "Mình đã hiểu yêu cầu đổi sang ngày 1 tháng 11 từ 5 giờ chiều đến 8 giờ tối, để ở bàn an ninh và gọi";
const suffix = " khi tới. Bạn muốn nhận hàng vào ngày 1 tháng 11 năm 2026, trong khoảng từ 5 giờ chiều đến 8 giờ tối, để ở bàn bảo vệ, và ghi chú là gọi khi tới. Bạn xác nhận giúp mình nhé?";
const event = (seq, speaker, turn, text) => ({ seq, at: "2026-10-31T10:00:00Z", type: "transcript", call_id: "e489b18c-571f-4c40-b33e-907c8883d928", payload: { speaker, turn_id: turn, text, final: false } });
const records = [event(6, "assistant", 1, "Xin chào"), event(18, "assistant", 1, greeting), event(20, "buyer", 1, " Please reschedule"), event(44, "buyer", 1, buyer), event(46, "assistant", 1, greeting + "Mình"), event(70, "assistant", 1, greeting + prefix), event(73, "assistant", 2, " khi tới."), event(112, "assistant", 2, suffix)];
const untouched = JSON.stringify(records);
records.forEach((record) => timeline.accept(record));
let utterances = timeline.snapshot();
assert.equal(utterances.length, 3);
assert.equal(utterances[0].payload.text, greeting, "later assistant output cannot overwrite the greeting bubble");
assert.equal(utterances[1].payload.text, buyer);
assert.equal(utterances[2].payload.text, prefix + suffix, "same-speaker speech continues across the mid-utterance logical-turn change");
assert.equal(new Set(utterances.map((record) => record.payload.utterance_id)).size, 3, "utterance identities remain distinct despite turn_id reuse");
assert.equal(utterances[2].payload.turn_id, 2, "raw logical turn metadata remains available");
assert.equal(JSON.stringify(records), untouched, "observation records are never mutated");
timeline.accept(records.at(-1));
assert.equal(timeline.snapshot()[2].payload.text, prefix + suffix, "repeated cumulative updates do not duplicate words");
timeline.accept(event(113, "assistant", 2, " khi tới. Corrected readback."));
utterances = timeline.snapshot();
assert.equal(utterances.length, 3);
assert.equal(utterances[2].payload.text, prefix + " khi tới. Corrected readback.", "a correction replaces its source contribution in place");
assert.equal(utterances[0].payload.text, greeting);
timeline.clear();
assert.equal(timeline.snapshot().length, 0, "source/generation reset clears utterance identities and cumulative baselines");
timeline.accept(event(1, "assistant", 1, "Fresh generation greeting"));
assert.equal(timeline.snapshot()[0].payload.text, "Fresh generation greeting");
console.log("PASS: real e489 speaker/turn reuse regression, cumulative-prefix removal, cross-turn continuation, corrections, dedupe and source reset.");
